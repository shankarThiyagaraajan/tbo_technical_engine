"""Writes docs/swing-review-sample.md: the 30 fixture setups of TE6's review, one row each, for a person to look over.

    uv run python -m scripts.swing_review_sheet            (from the repository root)

The cases come from tests/swing/review_sample.py (shaped fixtures, ten of each setup type); every number in the
sheet is the detector's, and the last column is the result of re-deriving it with plain loops. Fixtures are not
history: this shows the rules do what the plan says, not that they make money (that is the backtest, TE5).
"""

from __future__ import annotations

from pathlib import Path

from tests.swing.review_sample import SP, build_sample, check

OUT = Path(__file__).resolve().parents[1] / "docs" / "swing-review-sample.md"
RULES = {
    "base_breakout": (
        f"first close above the high of the {SP.base_breakout.base_bars} sessions before, base no deeper than "
        f"{SP.base_breakout.max_depth_pct:g}%, volume at least {SP.base_breakout.volume_ratio_min:g}x its mean, "
        "trend not down; stop under the base low"
    ),
    "ema_pullback": (
        f"uptrend; low within {SP.ema_pullback.touch_pct:g}% of the 20 (or 50) EMA, close back above it on an up day, "
        f"at least {SP.ema_pullback.min_pullback_pct:g}% off the recent high; buy one tick over the day's high"
    ),
    "week_52_high_breakout": (
        f"first close above the highest high of the {SP.week_52_high_breakout.lookback} sessions before, volume at "
        f"least {SP.week_52_high_breakout.volume_ratio_min:g}x, close in the upper half of the range; stop "
        f"{SP.week_52_high_breakout.stop_atr:g} ATR under the old high"
    ),
}


def main() -> None:
    cases = build_sample()
    lines = [
        "# TE6 review sample: 30 swing setups from fixtures",
        "",
        "Generated by `scripts/swing_review_sheet.py` from `tests/swing/review_sample.py`. **Fixtures, not recorded "
        "history**: there is no daily history in this repository yet, so this shows the rules behave as the plan "
        "says. The exit criterion (a manual review of 30 examples) is met on real data only once the market feed has "
        "recorded sessions; run the same detectors over them then.",
        "",
        "What to look at in each row: entry, stop and targets are on the 0.05 tick; the stop is below the entry and "
        "the targets above it; risk is between 0.5 and 4 ATR; the last column says whether plain-loop arithmetic on "
        "the raw bars agrees with the detector (the base or old high, the volume multiple, the EMA touch).",
        "",
    ]
    for kind, rule in RULES.items():
        lines += [f"## {kind}", "", f"Rule: {rule}.", ""]
        lines += [
            "| # | Case | Entry | Stop | T1 | T2 | Risk (ATR) | T1 / T2 (R) | Numbers the rule used | Re-derived |"
        ]
        lines += ["|---|---|---|---|---|---|---|---|---|---|"]
        for case in (c for c in cases if c.expected == kind):
            d = case.draft
            if d is None:
                lines.append(f"| {case.number} | {case.label} | no setup | | | | | | | FAIL |")
                continue
            risk = float(d.entry - d.stop)
            facts = ", ".join(f"{k} {v:.2f}" for k, v in d.facts.items())
            problems = check(case)
            lines.append(
                f"| {case.number} | {case.label} | {d.entry} | {d.stop} | {d.target_1} | {d.target_2} | "
                f"{risk / case.atr:.2f} | {float(d.target_1 - d.entry) / risk:.2f} / "
                f"{float(d.target_2 - d.entry) / risk:.2f} | "
                f"{facts} | {'ok' if not problems else '; '.join(problems)} |"
            )
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
